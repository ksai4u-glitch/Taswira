const fs=require('fs'),path=require('path'),assert=require('assert/strict'),{chromium}=require('playwright');
const shot=async(page,name)=>{if(process.argv[3]){fs.mkdirSync(process.argv[3],{recursive:true});await page.screenshot({path:path.join(process.argv[3],name+'.png')});}};
(async()=>{const browser=await chromium.launch({executablePath:'/usr/bin/chromium',args:['--no-sandbox']});try{
 const page=await browser.newPage({viewport:{width:1440,height:900}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));await page.route('https://**/*',r=>r.abort());
 await page.setContent(fs.readFileSync(process.argv[2],'utf8'));
 await page.waitForFunction(()=>document.getElementById('history').contentWindow.taswira?.seek);
 await page.locator('#history').evaluate(el=>el.contentWindow.taswira.seek('deep','gondwana',1.5));
 await shot(page,'green-intro');
 await page.locator('#history').evaluate(el=>el.contentWindow.taswira.exitVideo());
 await page.locator('#history').evaluate(el=>el.contentWindow.goTo(1,2));
 await page.waitForFunction(()=>Number(getComputedStyle(document.getElementById('history').contentDocument.getElementById('globe')).opacity)===0);
 await shot(page,'green-history');
 await page.frameLocator('#history').locator('a.back').click();
 await page.waitForFunction(()=>document.querySelector('[data-page=conflict]').getAttribute('aria-pressed')==='true');
 await page.locator('[data-page="history"]').click();
 assert.equal(await page.frameLocator('#history').locator('#card').isVisible(),true,'Embedded links must switch tabs without losing the history page');
 await page.locator('[data-page="conflict"]').click();
 await page.waitForFunction(()=>document.getElementById('conflict').contentDocument.querySelector('.leaflet-container'));
 const map=await page.locator('#conflict').elementHandle(),frame=await map.contentFrame();
 await frame.waitForFunction(()=>typeof anim!=='undefined');
 assert.equal(await frame.locator('h1').evaluate(el=>getComputedStyle(el).fontFamily.includes('Georgia')),true);
 assert.equal(await frame.locator('html').evaluate(el=>getComputedStyle(el).getPropertyValue('--surface-1').trim()),'#08120e');
 await shot(page,'green-conflict');
 await frame.locator('#theme').click();
 assert.equal(await frame.locator('html').getAttribute('data-theme'),'light');
 assert.equal(await frame.locator('html').evaluate(el=>getComputedStyle(el).getPropertyValue('--surface-1').trim()),'#f5f2e8');
 await shot(page,'green-conflict-light');
 await frame.locator('#theme').click();
 await frame.locator('#year-play').click();
 await frame.waitForFunction(()=>anim.on);
 await page.setViewportSize({width:390,height:844});
 await frame.locator('#drawer').click();assert.equal(await frame.locator('#drawer').getAttribute('aria-expanded'),'true');
 await frame.locator('#drawer').click();assert.equal(await frame.locator('#drawer').getAttribute('aria-expanded'),'false');
 await frame.waitForFunction(()=>document.getElementById('panel').getBoundingClientRect().height<=parseInt(getComputedStyle(document.documentElement).getPropertyValue('--peek'))+1);
 assert.equal(await frame.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await shot(page,'green-phone');
 assert.deepEqual(errors,[]);console.log('PASS: packaged two-page preview, Georgia headings, green dark theme, parchment light theme, conflict playback, phone drawer and no horizontal overflow.');
 }finally{await browser.close();}})().catch(e=>{console.error(e);process.exitCode=1});
